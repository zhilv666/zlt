//go:build linux

package app

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

const procdServiceName = "zhulingtai"

// procd* are variables rather than constants so tests can point the generated
// service at a temporary directory and observe the actions it would run without
// touching the host's real init scripts.
var (
	procdScriptPath = filepath.Join("/etc", "init.d", procdServiceName)
	procdRCDir      = filepath.Join("/etc", "rc.d")
	procdEUID       = os.Geteuid
	procdRunAction  = runProcdScript
)

func runProcdScript(action string) error {
	cmd := exec.Command(procdScriptPath, action)
	output, err := cmd.CombinedOutput()
	autostartLog().Debug("procd script", "command", strings.Join(cmd.Args, " "), "output", strings.TrimSpace(string(output)), "err", err)
	if err != nil {
		msg := strings.TrimSpace(string(output))
		if msg == "" {
			return err
		}
		return fmt.Errorf("%s %s: %s", procdScriptPath, action, msg)
	}
	return nil
}

// procdScriptContent renders an OpenWrt init script. procd passes the command
// words straight to exec, so each argument is POSIX single-quoted; there is no
// systemd-style quoting, specifier or environment expansion to escape.
func procdScriptContent(workdir, exe string, opts RunOptions) string {
	args := []string{exe, "--workdir", workdir, "run", "--listen", opts.Addr}
	if opts.PIDFile != "" {
		args = append(args, "--pid-file", opts.PIDFile)
	}
	for i := range args {
		args[i] = posixQuote(args[i])
	}
	return fmt.Sprintf(`#!/bin/sh /etc/rc.common
# Generated by zlt autostart.
# Manual edits are preserved unless "autostart enable" is run with explicit options.

START=99
STOP=10
USE_PROCD=1

start_service() {
	procd_open_instance
	procd_set_param command %s
	procd_set_param respawn 3600 2 0
	procd_set_param term_timeout 10
	procd_set_param stdout 1
	procd_set_param stderr 1
	procd_close_instance
}
`, strings.Join(args, " "))
}

func posixQuote(value string) string {
	return "'" + strings.ReplaceAll(value, "'", `'\''`) + "'"
}

func procdServiceEnabled() bool {
	links, err := filepath.Glob(filepath.Join(procdRCDir, "S*"+procdServiceName))
	return err == nil && len(links) > 0
}

// procdRequiresRoot reports a clear error instead of letting the write fail with
// a bare permission denied: /etc/init.d and /etc/rc.d are root-owned on OpenWrt.
func procdRequiresRoot(action string) error {
	if procdEUID() == 0 {
		return nil
	}
	return fmt.Errorf("autostart %s requires root (write access to %s); retry with sudo", action, filepath.Dir(procdScriptPath))
}

func writeProcdScript(path, content string, update bool) error {
	if update {
		return os.WriteFile(path, []byte(content), 0o755)
	}
	// Re-enabling an existing script must preserve manual edits. Explicit CLI
	// options (--listen/--pid-file) request regeneration.
	file, err := os.OpenFile(path, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0o755)
	if os.IsExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	_, err = file.WriteString(content)
	closeErr := file.Close()
	if err != nil {
		return err
	}
	return closeErr
}

func enableProcdAutostart(opts RunOptions, update bool) error {
	if err := procdRequiresRoot("enable"); err != nil {
		autostartLog().Error("enable: permission check failed", "err", err)
		return err
	}

	exe, err := os.Executable()
	if err != nil {
		autostartLog().Error("enable: resolve executable failed", "err", err)
		return err
	}
	workdir, err := os.Getwd()
	if err != nil {
		autostartLog().Error("enable: getwd failed", "err", err)
		return err
	}
	if strings.ContainsAny(workdir+exe+opts.Addr+opts.PIDFile, "\r\n\x00") {
		return fmt.Errorf("autostart paths and arguments must not contain newlines or NUL")
	}

	if err := os.MkdirAll(filepath.Dir(procdScriptPath), 0o755); err != nil {
		autostartLog().Error("enable: mkdir failed", "err", err)
		return err
	}
	if err := writeProcdScript(procdScriptPath, procdScriptContent(workdir, exe, opts), update); err != nil {
		autostartLog().Error("enable: write script failed", "err", err)
		return err
	}
	// O_CREATE honours the umask, so pin the executable bit the init system needs.
	if err := os.Chmod(procdScriptPath, 0o755); err != nil {
		autostartLog().Error("enable: chmod script failed", "err", err)
		return err
	}
	autostartLog().Info("enabled", "scope", "system", "script", procdScriptPath)

	if err := procdRunAction("enable"); err != nil {
		return err
	}

	fmt.Printf("autostart enabled (system): %s\n", procdScriptPath)
	// `start` must not run twice: procd would spawn a second instance rather
	// than notice the first. Only start when this host is not already serving.
	if err := ensureProcdRunning(); err != nil {
		return err
	}
	if update {
		fmt.Printf("to apply changes to an already running service: %s restart\n", procdScriptPath)
	}
	return nil
}

// ensureProcdRunning starts the service only when no instance of this
// application holds the single-instance lock. That covers both a fresh enable
// and the web-UI enable (where this very process is the running instance).
func ensureProcdRunning() error {
	lock, err := readPIDFile(defaultPIDFile())
	if err == nil && processMatches(lock.PID, lock.Exe) {
		autostartLog().Debug("enable: already running", "pid", lock.PID)
		return nil
	}
	return procdRunAction("start")
}

func disableProcdAutostart() error {
	if err := procdRequiresRoot("disable"); err != nil {
		autostartLog().Error("disable: permission check failed", "err", err)
		return err
	}

	_ = procdRunAction("stop")
	_ = procdRunAction("disable")
	if err := os.Remove(procdScriptPath); err != nil && !os.IsNotExist(err) {
		autostartLog().Error("disable: remove script failed", "err", err)
		return err
	}

	fmt.Printf("autostart disabled (system)\n")
	return nil
}

func procdAutostartStatus() (AutoStartStatus, error) {
	if _, err := os.Stat(procdScriptPath); err != nil {
		if os.IsNotExist(err) {
			return AutoStartStatus{
				Supported: true,
				Enabled:   false,
				Status:    "disabled",
				UnitPath:  procdScriptPath,
				Message:   procdStatusHint(),
			}, nil
		}
		return AutoStartStatus{}, err
	}

	enabled := procdServiceEnabled()
	status := "disabled"
	if enabled {
		status = "enabled"
	}
	return AutoStartStatus{
		Supported: true,
		Enabled:   enabled,
		Status:    status,
		UnitPath:  procdScriptPath,
		Message:   procdStatusHint(),
	}, nil
}

// procdStatusHint keeps the web UI honest about who can change the setting:
// OpenWrt's init scripts are system-wide and root-owned.
func procdStatusHint() string {
	if procdEUID() == 0 {
		return ""
	}
	return "OpenWrt procd service is system-wide; run zlt autostart with sudo"
}
